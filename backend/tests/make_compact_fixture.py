def build_fixture() -> dict:
    cases = []
    for name, algo, params, cost, workload in CASES:
        full = simulate(workload, SimConfig(algo, params, cost))
        cases.append({"name": name, "full": json.loads(json.dumps(full)),
                      "compact": json.loads(json.dumps(compact_result(full)))})
    return {"note": "Generated by backend/tests/make_compact_fixture.py. Do not edit by hand.", "cases": cases}


if __name__ == "__main__":
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(build_fixture(), indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print("wrote", FIXTURE, FIXTURE.stat().st_size, "bytes")
